/*
 * release PON serdes register interface reset
 */
static inline void __psds_csr_out_of_reset(void)
{
#ifndef CONFIG_CORTINA_BOARD_FPGA
    AAL_GLB_REG_FIELD_WRITE(GLOBAL_PON_CNTL, psds_reg_rst_n, 0);
    ca_mdelay(1);
    AAL_GLB_REG_FIELD_WRITE(GLOBAL_PON_CNTL, psds_reg_rst_n, 1);
    ca_mdelay(100);
#endif
}

/*
 * bring PON serdes analog and digital logic out of reset
 */
static inline void 
__psds_ad_out_of_reset(void)
{
#ifndef CONFIG_CORTINA_BOARD_FPGA
	AAL_GLB_REG_FIELD_WRITE(GLOBAL_PSDS_INIT_CNTL,POW_PCIX,1);
	ca_mdelay(100);
#endif
}

/*
 * bring the PON serdes interface Gearbox and related logic out of reset
 */
static inline void 
__psds_gbox_out_of_reset(void)
{
#ifndef CONFIG_CORTINA_BOARD_FPGA
    AAL_GLB_REG_FIELD_WRITE(GLOBAL_PON_CNTL, pon_serdes_rst_n, 0);
    ca_mdelay(1);
    AAL_GLB_REG_FIELD_WRITE(GLOBAL_PON_CNTL, pon_serdes_rst_n, 1);
    ca_mdelay(100);
#endif
}

static inline void 
__psds_gbox_init(
	ca_uint32_t rx_bit_order, 
	ca_uint32_t tx_bit_order)
{
#ifndef CONFIG_CORTINA_BOARD_FPGA
    ca_printf("__psds_gbox_init  rx_bit_order %d, tx_bit_order %d\r\n", rx_bit_order, tx_bit_order);
    AAL_PON_REG_FIELD_WRITE(PSDS_GBOX_CTRL, rx_bit_ordering, rx_bit_order);
    AAL_PON_REG_FIELD_WRITE(PSDS_GBOX_CTRL, tx_bit_ordering, tx_bit_order);
    ca_mdelay(1);
#endif
}

